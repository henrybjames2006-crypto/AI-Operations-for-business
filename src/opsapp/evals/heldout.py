def _c(
    n: int,
    kind: str,
    text: str,
    sender: str,
    customer: str | None,
    items: dict[str, str | None],
    *,
    timeframe: str | None = None,
    flagged: bool = False,
    unsupported: int = 0,
    state: str | None = None,
    total: str | None = None,
) -> Case:
    return Case(
        f"heldout-{n:02d}",
        f"heldout_{kind}",
        text,
        sender,
        customer=customer,
        items=items,
        timeframe=timeframe,
        flagged=flagged,
        unsupported=unsupported,
        expect_state=state,
        expect_total=total,
    )


