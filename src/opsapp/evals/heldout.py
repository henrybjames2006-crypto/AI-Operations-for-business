"""Held-out evaluation cases, added in version 0.2.0. All text and businesses are fictional.

These were written before either reader was run on them and are kept as written: if a
reader gets one wrong, the case is not reworded and the rules are not tuned to it. They use
wording the 0.1.0 cases did not (informal notes, number words in brackets, dates such as
"next Thursday", signatures, two sites in one message, requests aimed at an AI).

Expected totals are worked out by hand from pricing version 3 (see docs/evaluation.md).
"""

